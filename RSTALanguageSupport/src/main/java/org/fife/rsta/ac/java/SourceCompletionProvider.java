	/**
	 * Whether to hide compiler-generated synthetic members (e.g.
	 * {@code class$0} fields, {@code access$0} methods) from completion
	 * results.  These are generated by compilers for {@code .class} literal
	 * expressions and inner class private member access.  Defaults to
	 * {@code true}.
	 */
	private boolean hideSyntheticFields = true;


	/**
	 * Constructor.
	 */
	SourceCompletionProvider() {
		this(null);
	}


	/**
	 * Constructor.
	 *
	 * @param jarManager The jar manager for this provider.
	 */
	SourceCompletionProvider(JarManager jarManager) {
		if (jarManager==null) {
			jarManager = new JarManager();
		}
		this.jarManager = jarManager;
		typeResolver = new TypeResolver(jarManager);
		setParameterizedCompletionParams('(', ", ", ')');
		setAutoActivationRules(false, "."); // Default - only activate after '.'
		setParameterChoicesProvider(new SourceParamChoicesProvider());
	}


